describe("the leading zero survives — the reason this is not a CSV", () => {
  it("comes back out of the real file as eleven characters, not a number", async () => {
    await lead("bsystems", "Zero Lead", { number: "01012345678" });

    const { grid } = await readBack("bsystems");
    const phone = rowFor(grid, "Zero Lead")[col("phone")];

    expect(typeof phone).toBe("string");
    expect(phone).toBe("01012345678");
    /* the failure mode spelled out: a CSV (or a numeric cell) gives this */
    expect(phone).not.toBe(1012345678);
    expect(String(phone).startsWith("0")).toBe(true);
    expect(String(phone)).toHaveLength(11);
  });

  it("the cell is a TEXT cell in the SpreadsheetML, not a formatted number", async () => {
    await lead("bsystems", "Zero Lead", { number: "01012345678" });
    const { buffer } = await readBack("bsystems");

    const zip = unzipSync(new Uint8Array(buffer));
    const sheet = strFromU8(zip["xl/worksheets/sheet1.xml"]!);
    const shared = strFromU8(zip["xl/sharedStrings.xml"]!);

    /* the number lives in sharedStrings — i.e. it is a string, and the zero is
       part of it — and the cell that points at it is typed `t="s"`. A numeric
       cell would carry <v>1012345678</v> with no type at all, and no amount of
       display formatting would put the zero back in the data. */
    expect(shared).toContain("<t>01012345678</t>");
    const index = shared.split("<si>").findIndex((si) => si.includes("<t>01012345678</t>")) - 1;
    expect(index).toBeGreaterThanOrEqual(0);
    expect(sheet).toContain(`t="s"><v>${index}</v>`);
    expect(sheet).not.toContain("<v>1012345678</v>");
  });

  it("a zero-prefixed number is preserved for EVERY lead in the file", async () => {
    for (let i = 0; i < 12; i++) {
      await lead("bsystems", `Lead ${i}`, { number: `0101234567${i}` });
    }
    const { grid } = await readBack("bsystems");
    const phones = grid.slice(1).map((r) => r[col("phone")]);
    expect(phones).toHaveLength(12);
    for (const p of phones) {
      expect(typeof p).toBe("string");
      expect(String(p).startsWith("0")).toBe(true);
    }
  });
});

