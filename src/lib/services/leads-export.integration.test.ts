describe("real typed cells — not a grid of strings", () => {
  it("dates come back as DATES, carrying the CAIRO day", async () => {
    const l = await lead("bsystems", "Dated Lead");
    /* 2026-10-05 23:30 UTC is 2026-10-06 01:30 in Cairo. A sheet that handed
       Prisma's Date straight to the cell would print the 5th while every screen
       in the product says the 6th — one day's disagreement, on the column he
       would sort by. */
    const created = new Date("2026-10-05T23:30:00.000Z");
    await db.lead.update({ where: { id: l.id }, data: { createdAt: created } });

    const { grid } = await readBack("bsystems");
    const cell = rowFor(grid, "Dated Lead")[col("created")];

    expect(cell).toBeInstanceOf(Date);
    expect(typeof cell).not.toBe("string");
    const asDate = cell as Date;
    /* the serial is the Cairo wall clock, so reading it back as UTC gives the
       Cairo hands — which is exactly what `formatCairo` prints on screen */
    expect(toMinute(asDate)).toBe("2026-10-06T02:30:00.000Z"); // Cairo is UTC+3 in October (DST)
    expect(utcToCairo(created).date).toBe("2026-10-06");
  });

  it("a follow-up with NO chosen time is a DATE cell with no clock on it", async () => {
    const l = await lead("bsystems", "Follow Lead");
    await db.followUp.create({
      data: {
        leadId: l.id,
        context: "initial",
        /* ADR-061's 09:00 Cairo default — a time nobody chose */
        dueAt: new Date("2026-11-10T07:00:00.000Z"),
        dueTimeSet: false,
        method: "call",
      },
    });

    const { grid, buffer } = await readBack("bsystems");
    const cell = rowFor(grid, "Follow Lead")[col("nextFollowUp")];
    expect(cell).toBeInstanceOf(Date);
    /* midnight Cairo — ADR-063's rule (never print a clock nobody chose), and
       it is what makes Excel's "equals 10/11/2026" filter match */
    expect(toMinute(cell as Date)).toBe("2026-11-10T00:00:00.000Z");

    const styles = strFromU8(unzipSync(new Uint8Array(buffer))["xl/styles.xml"]!);
    expect(styles).toContain('formatCode="dd/mm/yyyy"');
  });

  it("a follow-up with a CHOSEN time keeps its clock", async () => {
    const l = await lead("bsystems", "Timed Lead");
    await db.followUp.create({
      data: {
        leadId: l.id,
        context: "initial",
        dueAt: new Date("2026-11-10T14:45:00.000Z"), // 16:45 Cairo
        dueTimeSet: true,
        method: "call",
      },
    });

    const { grid } = await readBack("bsystems");
    const cell = rowFor(grid, "Timed Lead")[col("nextFollowUp")];
    expect(toMinute(cell as Date)).toBe("2026-11-10T16:45:00.000Z");
  });

  it("money is a NUMBER, in pounds, with a money format", async () => {
    const l = await lead("bsystems", "Valued Lead");
    await db.proposal.create({
      /* stored in piasters (ADR-018) — 1,500.50 EGP */
      data: { leadId: l.id, service: "Audit", estimatedValue: 150_050 },
    });

    const { grid, buffer } = await readBack("bsystems");
    const cell = rowFor(grid, "Valued Lead")[col("value")];
    expect(typeof cell).toBe("number");
    expect(cell).toBe(1500.5);
    /* not the minor units, and not a string with a currency glued on */
    expect(cell).not.toBe(150050);
    expect(cell).not.toBe("EGP 1,500.50");

    const styles = strFromU8(unzipSync(new Uint8Array(buffer))["xl/styles.xml"]!);
    expect(styles).toContain('formatCode="#,##0.00"');
  });

  it("a won lead with no proposal still carries its won value", async () => {
    const bf = await lead("byteforce", "Won Without Proposal");
    await db.lead.update({ where: { id: bf.id }, data: { stage: "won" } });
    await db.wonInfo.create({
      data: {
        leadId: bf.id,
        estimatedValue: 80_000_00,
        technicalOwner: "Nour",
        collectedAmount: 0,
      },
    });

    const { grid } = await readBack("byteforce");
    expect(rowFor(grid, "Won Without Proposal")[col("value")]).toBe(80_000);
  });

  it("the tally is a number — including the honest ZERO", async () => {
    const tried = await lead("bsystems", "Tried Thrice");
    await db.lead.update({
      where: { id: tried.id },
      data: { noAnswer: true, noAnswerCount: 3 },
    });
    await lead("bsystems", "Never Tried");

    const { grid } = await readBack("bsystems");
    expect(rowFor(grid, "Tried Thrice")[col("noAnswer")]).toBe(3);
    /* 0, not blank: the column has to sum and sort, which is what ADR-064's
       counter was asked for */
    expect(rowFor(grid, "Never Tried")[col("noAnswer")]).toBe(0);
  });

  it("every column of a bare lead is either a value or EMPTY — never the string \"null\"", async () => {
    await lead("bsystems", "Bare Lead");
    const { grid } = await readBack("bsystems");
    const row = rowFor(grid, "Bare Lead");
    expect(row).toHaveLength(LEAD_EXPORT_COLUMNS.length);
    for (const cell of row) {
      expect(cell).not.toBe("null");
      expect(cell).not.toBe("undefined");
      expect(cell).not.toBe("NaN");
    }
    /* the optional record columns are genuinely blank */
    expect(row[col("nextFollowUp")]).toBe(null);
    expect(row[col("latestMeeting")]).toBe(null);
    expect(row[col("value")]).toBe(null);
    expect(row[col("lostReason")]).toBe(null);
  });
});

