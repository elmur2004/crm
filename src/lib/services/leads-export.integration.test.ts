/* ============================================================================
   ADR-083 — THE FILE ITSELF, read back.

   The whole reason this is a real .xlsx and not a CSV is that Excel silently
   corrupts two things in a CSV, and both of them are the point of the sheet:

     · an Egyptian mobile loses its leading zero ("01012345678" → 1012345678),
       corrupting the single field he calls the lead on;
     · Arabic names mis-decode without a byte-order mark.

   A test that only asserted "a buffer came back" would prove neither. So every
   case here GENERATES THE REAL FILE and then PARSES IT BACK — with
   `read-excel-file`, a different library by the same author with its own XML
   reader, and for the two structural claims (is the phone really a text cell,
   is the sheet really right-to-left) by unzipping the archive and reading the
   SpreadsheetML the way Excel will.

   The fixtures are deliberately nasty: a leading zero, an Arabic name and an
   Arabic company, a lead in every one of the four statuses he named, a
   cross-company twin that must be ABSENT, a lead with no records at all, and a
   zero in the tally column.
   ========================================================================== */

const actor: Actor = { id: null, label: "Test Admin" };

let seq = 0;
function lead(
  brand: "bsystems" | "byteforce",
  name: string,
  extra?: { number?: string; companyName?: string; email?: string; position?: string; industry?: string },
) {
  seq += 1;
  return createLead(
    brand,
    {
      name,
      /* every number in this product starts with a zero — that is the fixture */
      number: extra?.number ?? `0100000${String(1000 + seq)}`,
      type: "cold_call",
      ...(extra?.companyName ? { companyName: extra.companyName } : {}),
      ...(extra?.email ? { email: extra.email } : {}),
      ...(extra?.position ? { position: extra.position } : {}),
      ...(extra?.industry ? { industry: extra.industry } : {}),
    },
    actor,
  );
}

/** The sheet as a grid of cells, straight out of the generated bytes. */
async function readBack(company: "bsystems" | "byteforce", locale: "en" | "ar" = "en") {
  const { buffer, filename, rows } = await buildLeadsWorkbook(company, locale);
  const grid = await readSheet(buffer);
  const sheets = await readXlsxFile(buffer);
  return { grid, filename, rows, buffer, sheetName: sheets[0]?.sheet };
}

/** An XLSX date is a FRACTION OF A DAY in a float, so a value like 14:00 is
    not exactly representable and a write-then-read costs under a millisecond
    (13:59:59.999 for 14:00). That is below anything a date format can show —
    Excel rounds a serial to the unit it is printing — so these assertions round
    to the minute too, which is the precision the cells are formatted at.
    Equality to the MINUTE is the claim; the day is asserted separately. */
function toMinute(d: Date): string {
  return new Date(Math.round(d.getTime() / 60_000) * 60_000).toISOString();
}

/** A column's index by its key, so a test never counts letters. */
function col(key: string): number {
  const i = LEAD_EXPORT_COLUMNS.findIndex((c) => c.key === key);
  if (i < 0) throw new Error(`no export column "${key}"`);
  return i;
}

/** The data row for a lead, found by name. */
function rowFor(grid: unknown[][], name: string): unknown[] {
  const row = grid.slice(1).find((r) => r[col("name")] === name);
  if (!row) throw new Error(`no row for "${name}" in the generated file`);
  return row;
}

