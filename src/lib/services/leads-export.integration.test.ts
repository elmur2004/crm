describe("EVERY lead, ever — and the column that says which", () => {
  it("live, won, lost AND archived all appear, each with the right status", async () => {
    const live = await lead("bsystems", "Still Live");
    await db.lead.update({ where: { id: live.id }, data: { stage: "following_up" } });

    const won = await lead("bsystems", "Closed Won");
    await db.lead.update({ where: { id: won.id }, data: { stage: "won" } });

    const lost = await lead("bsystems", "Gone Cold");
    await db.lead.update({ where: { id: lost.id }, data: { stage: "lost" } });
    await db.lostInfo.create({ data: { leadId: lost.id, reason: "Chose a cheaper vendor" } });

    const archived = await lead("bsystems", "Put Away");
    await db.lead.update({
      where: { id: archived.id },
      data: { archived: true, archivedAt: new Date() },
    });

    const { grid, rows } = await readBack("bsystems");
    expect(rows).toBe(4);
    expect(grid).toHaveLength(5); // header + four

    expect(rowFor(grid, "Still Live")[col("status")]).toBe("Live");
    expect(rowFor(grid, "Closed Won")[col("status")]).toBe("Won");
    expect(rowFor(grid, "Gone Cold")[col("status")]).toBe("Lost");
    expect(rowFor(grid, "Put Away")[col("status")]).toBe("Archived");
    expect(rowFor(grid, "Gone Cold")[col("lostReason")]).toBe("Chose a cheaper vendor");
  });

  it("an ARCHIVED WON lead reads Archived in Status and Won in Stage", async () => {
    /* the overlap, decided in lib/crm/leads-export.ts: archived wins, because
       it is the answer to "where did this lead go" — and nothing is lost,
       because the Stage column beside it still counts the win */
    const l = await lead("bsystems", "Won Then Filed");
    await db.lead.update({
      where: { id: l.id },
      data: { stage: "won", archived: true, archivedAt: new Date() },
    });

    const { grid } = await readBack("bsystems");
    const row = rowFor(grid, "Won Then Filed");
    expect(row[col("status")]).toBe("Archived");
    expect(row[col("stage")]).toBe("Won");
  });

  it("the row count matches the DATABASE — archived included, filters irrelevant", async () => {
    for (let i = 0; i < 7; i++) await lead("bsystems", `Active ${i}`);
    for (let i = 0; i < 5; i++) {
      const l = await lead("bsystems", `Filed ${i}`);
      await db.lead.update({ where: { id: l.id }, data: { archived: true } });
    }
    /* and a handful of the other company's, which must not be in this file */
    for (let i = 0; i < 3; i++) await lead("byteforce", `Foreign ${i}`);

    const inDb = await db.lead.count({ where: { brand: "bsystems" } });
    expect(inDb).toBe(12);

    const { grid, rows } = await readBack("bsystems");
    expect(rows).toBe(inDb);
    expect(grid.slice(1)).toHaveLength(inDb);
    const names = grid.slice(1).map((r) => r[col("name")]);
    expect(names).toContain("Filed 0");
    expect(names.filter((n) => String(n).startsWith("Foreign"))).toEqual([]);
  });

  it("one company's file never contains the other's leads — in either direction", async () => {
    await lead("bsystems", "B-Systems Client");
    await lead("byteforce", "ByteForce Client");

    const bs = await readBack("bsystems");
    expect(bs.rows).toBe(1);
    expect(bs.grid[1]![col("name")]).toBe("B-Systems Client");

    const bf = await readBack("byteforce");
    expect(bf.rows).toBe(1);
    expect(bf.grid[1]![col("name")]).toBe("ByteForce Client");
  });

  it("an empty company still produces a valid file with its header row", async () => {
    const { grid, rows } = await readBack("byteforce");
    expect(rows).toBe(0);
    expect(grid).toHaveLength(1);
    expect(grid[0]).toHaveLength(LEAD_EXPORT_COLUMNS.length);
  });

  it("the rows are newest-added first — the Leads table's own default order", async () => {
    const a = await lead("bsystems", "Oldest");
    const b = await lead("bsystems", "Middle");
    const c = await lead("bsystems", "Newest");
    await db.lead.update({ where: { id: a.id }, data: { createdAt: new Date("2026-01-01T09:00:00Z") } });
    await db.lead.update({ where: { id: b.id }, data: { createdAt: new Date("2026-05-01T09:00:00Z") } });
    await db.lead.update({ where: { id: c.id }, data: { createdAt: new Date("2026-09-01T09:00:00Z") } });

    const { grid } = await readBack("bsystems");
    expect(grid.slice(1).map((r) => r[col("name")])).toEqual(["Newest", "Middle", "Oldest"]);
  });
});

