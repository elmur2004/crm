describe("the download itself", () => {
  it("is named for the company and the Cairo day, and the two cannot collide", async () => {
    await lead("bsystems", "Anybody");
    const today = utcToCairo(new Date()).date;
    const bs = await buildLeadsWorkbook("bsystems", "en");
    const bf = await buildLeadsWorkbook("byteforce", "en");
    expect(bs.filename).toBe(`b-systems-leads-${today}.xlsx`);
    expect(bf.filename).toBe(`byteforce-leads-${today}.xlsx`);
    expect(bs.filename).not.toBe(bf.filename);
  });

  it("is a real ZIP container with the parts Excel opens", async () => {
    await lead("bsystems", "Anybody");
    const { buffer } = await readBack("bsystems");
    /* "PK" — if this were a CSV with a different extension, Excel would still
       open it and silently eat the leading zeros, which is the bug */
    expect(buffer.subarray(0, 2).toString("latin1")).toBe("PK");
    const entries = Object.keys(unzipSync(new Uint8Array(buffer)));
    expect(entries).toContain("xl/worksheets/sheet1.xml");
    expect(entries).toContain("xl/styles.xml");
    expect(entries).toContain("xl/sharedStrings.xml");
    expect(entries).toContain("[Content_Types].xml");
  });

  it("the header row is frozen, so it survives ten thousand rows of scrolling", async () => {
    await lead("bsystems", "Anybody");
    const { buffer } = await readBack("bsystems");
    const sheet = strFromU8(unzipSync(new Uint8Array(buffer))["xl/worksheets/sheet1.xml"]!);
    expect(sheet).toContain('ySplit="1"');
    expect(sheet).toContain('state="frozen"');
  });

  it("has the twenty-one columns, each with a header and no duplicate key", async () => {
    const keys = LEAD_EXPORT_COLUMNS.map((c) => c.key);
    expect(keys).toHaveLength(21);
    expect(new Set(keys).size).toBe(21);
    for (const c of LEAD_EXPORT_COLUMNS) {
      expect(c.header.en.length, c.key).toBeGreaterThan(0);
      expect(c.header.ar.length, c.key).toBeGreaterThan(0);
      /* every header is translated — no Arabic column falls back to English */
      expect(c.header.ar, c.key).not.toBe(c.header.en);
      expect(c.width, c.key).toBeGreaterThan(0);
    }
  });
});
