describe("Arabic round-trips", () => {
  it("an Arabic name and company come back byte-for-byte", async () => {
    await lead("bsystems", "محمد عبد الرحمن", {
      companyName: "شركة النيل للتجارة",
      position: "مدير المشتريات",
      industry: "الإنشاءات",
    });

    const { grid } = await readBack("bsystems");
    const row = rowFor(grid, "محمد عبد الرحمن");
    expect(row[col("name")]).toBe("محمد عبد الرحمن");
    expect(row[col("company")]).toBe("شركة النيل للتجارة");
    expect(row[col("position")]).toBe("مدير المشتريات");
    expect(row[col("industry")]).toBe("الإنشاءات");
  });

  it("the HEADERS follow the viewer's language", async () => {
    await lead("bsystems", "Anybody");

    const en = await readBack("bsystems", "en");
    expect(en.grid[0]![col("name")]).toBe("Name");
    expect(en.grid[0]![col("status")]).toBe("Status");
    expect(en.sheetName).toBe("Leads");

    const ar = await readBack("bsystems", "ar");
    expect(ar.grid[0]![col("name")]).toBe("الاسم");
    expect(ar.grid[0]![col("status")]).toBe("الحالة");
    expect(ar.grid[0]![col("phone")]).toBe("الرقم");
    expect(ar.sheetName).toBe("العملاء المحتملون");
    /* and the English file is untouched by the Arabic one existing */
    expect(ar.grid[0]).not.toEqual(en.grid[0]);
  });

  it("an Arabic export sets the sheet RIGHT-TO-LEFT; an English one does not", async () => {
    await lead("bsystems", "Anybody");

    const sheetXml = async (locale: "en" | "ar") => {
      const { buffer } = await readBack("bsystems", locale);
      return strFromU8(unzipSync(new Uint8Array(buffer))["xl/worksheets/sheet1.xml"]!);
    };

    expect(await sheetXml("ar")).toContain('rightToLeft="1"');
    expect(await sheetXml("en")).not.toContain("rightToLeft");
  });

  it("the translated STAGE and TYPE labels are the ones the screens use", async () => {
    const l = await lead("bsystems", "Arabic Stage");
    await db.lead.update({ where: { id: l.id }, data: { stage: "negotiation" } });

    const { grid } = await readBack("bsystems", "ar");
    const row = rowFor(grid, "Arabic Stage");
    expect(row[col("stage")]).toBe("تفاوض"); // labels.ts's own stageMsgs
    expect(row[col("type")]).toBe("اتصال مباشر"); // cold_call
    expect(row[col("whatsapp")]).toBe("لا");
  });
});

